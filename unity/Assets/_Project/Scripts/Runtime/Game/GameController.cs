using System.Collections;
using System.Collections.Generic;
using System.Text;
using SevenSteps.Contracts;
using SevenSteps.Core;
using SevenSteps.Game.Telemetry;
using SevenSteps.Game.UI;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.InputSystem;
using UnityEngine.InputSystem.UI;

namespace SevenSteps.Game
{
    /// <summary>
    /// Game scene root (states Game and Result, docs/architecture.md 8, 11.1). Owns the <see cref="GameSession"/>,
    /// the board view and the HUD. Input becomes Commands sent to the session; the session owns the State and the input lock.
    /// Listens to <see cref="GameSession.Updated"/> for messages, sound and save, and to <see cref="AppFlow.Changed"/> for
    /// stage changes and the result panel.
    /// Playing Game.unity directly in the editor runs the same bootstrap as Boot (startLevel / replay below act like -level / -replay).
    /// </summary>
    public sealed class GameController : MonoBehaviour
    {
        static readonly Dictionary<GameEventType, string> Messages = new Dictionary<GameEventType, string>
        {
            { GameEventType.Choose, "행운의 7번째 걸음. 이 몸을 어떻게 할까?" },
            { GameEventType.Stone, "KEEP. 몸이 석상이 되었다. 다음 몸은 출발점에서 깨어난다." },
            { GameEventType.Switch, "SWITCH. 이 자리가 새 출발점이 되었다." },
            { GameEventType.Bridge, "7번째 걸음으로 구덩이에 몸을 던졌다. 다리가 되었다." },
            { GameEventType.Seal, "금 간 바닥 위에서 석상이 되었다. 바닥이 영원히 굳었다." },
            { GameEventType.Fall, "구덩이에 떨어졌다. 7번째 걸음이 아니면 아무것도 남지 않는다." },
            { GameEventType.Vanish, "출발점에서는 석상이 될 수 없다. 몸 하나를 잃었다." },
            { GameEventType.Crumble, "금 간 바닥이 무너졌다." },
            { GameEventType.Win, "7번째 걸음으로 출구에 닿았다!" },
            { GameEventType.Lose, "몸을 모두 잃었다. Z로 되돌리거나 R로 다시 시작." },
            { GameEventType.Undo, "한 걸음 되돌렸다." },
            { GameEventType.Restart, "처음부터." },
            { GameEventType.Flip, "7번째 걸음으로 레버를 당겼다. 벽이 뒤집혔다." },
        };

        const string ChooseNudge = "먼저 고르자: K = KEEP (석상), X = SWITCH (새 출발점).";

        [Tooltip("Generated by Seven Steps > Build Assets and Scene")]
        public GameAssets assets;
        [Tooltip("Data/AppConfig.asset. Used when this scene is played without Boot.")]
        public AppConfig config;
        [Tooltip("Editor only, when played without Boot: 1-based stage (like -level)")]
        public int startLevel = 1;
        [Tooltip("Editor only, when played without Boot: replay letters U D L R K X (like -replay)")]
        public string replay = "";

        Level[] levels;
        GameSession session;
        AppFlow flow;
        SaveSystem save;
        LaunchOptions launch;
        string message;
        HudView hud;
        BoardView board;
        AudioSource sfx;
        Camera cam;
        int loadedStage = -1;
        TelemetryRecorder recorder;
        readonly Dictionary<int, string> hintCache = new Dictionary<int, string>();

        public GameSession Session => session;
        public int LevelIndex => flow.Stage;
        public int LevelCount => levels.Length;
        public Level[] Levels => levels;

        /// Raised when a stage is loaded through the flow, with how it was entered (boot, url, next, select, again).
        public event Action<int, string> StageEntered;
        /// Raised just before a stage is loaded, with the 0-based stage about to start (Session.State is still the old one).
        public event Action<int> StageLeaving;
        /// Raised for HUD-only actions that do not touch the session (hint).
        public event Action HintShown;

        string nextVia = TelemetryNames.Via.Boot;

        /// Set by Bootstrap.Run: the next stage entry is the first of this app run (telemetry via = boot/url).
        internal static bool FirstEntryPending;
        /// Scene played directly in the editor (or a build without Boot): the start level came from startLevel, not the URL.
        bool levelFromInspector;

        void Awake()
        {
            Application.targetFrameRate = 60;
            if (!Services.Has<AppFlow>())
            {
                // Played directly in the editor: same bootstrap as the Boot scene, with this object's debug start values.
                var opts = Bootstrap.ReadLaunchOptions();
                if (!opts.DirectToGame) { opts.Level = Mathf.Max(1, startLevel); levelFromInspector = true; }
                if (string.IsNullOrEmpty(opts.Replay)) opts.Replay = replay ?? "";
                Bootstrap.Run(config, opts, enterFirstScreen: false);
            }
            flow = Services.Get<AppFlow>();
            save = Services.Get<SaveSystem>();
            launch = Services.Get<LaunchOptions>();
            var cfg = Services.Get<AppConfig>();

            Ui.Font = assets.font;
            levels = LevelCatalog.Load(assets);

            cam = Camera.main;
            cam.clearFlags = CameraClearFlags.SolidColor;
            cam.backgroundColor = assets.background;
            sfx = gameObject.AddComponent<AudioSource>();
            sfx.playOnAwake = false;
            ApplyVolume(save.Settings);
            save.SettingsChanged += ApplyVolume;

            if (FindAnyObjectByType<EventSystem>() == null)
                new GameObject("EventSystem", typeof(EventSystem), typeof(InputSystemUIInputModule));

            hud = new HudView(this, levels.Length, save);
            board = gameObject.AddComponent<BoardView>();
            var tiles = cfg.tileSet != null ? cfg.tileSet : assets.tileSet;
            if (tiles == null) throw new InvalidOperationException("[SevenSteps] No TileSet: set AppConfig.tileSet or GameAssets.tileSet");
            board.Init(tiles, hud.LabelLayer, cam);

            session = new GameSession(board);
            board.Hurry = () => session.QueuedCount > 0;
            session.Updated += OnSessionUpdated;
            session.Presented += OnPresented;
            if (Services.Get<ITelemetry>() is HttpTelemetry http) recorder = new TelemetryRecorder(this, session, http);
            flow.Changed += OnFlowChanged;
        }

        void Start()
        {
            // Boot -> Game (or editor direct play): enter the game state now that the scene exists.
            if (flow.State == AppState.Boot)
            {
                nextVia = launch.DirectToGame && !levelFromInspector ? TelemetryNames.Via.Url : TelemetryNames.Via.Boot;
                flow.GoToGame(Mathf.Clamp(launch.DirectToGame ? launch.Level - 1 : 0, 0, levels.Length - 1));
            }
            else if (flow.State == AppState.Game)
            {
                // Boot -> Game for ?level= / -level, or StageSelect -> Game.
                nextVia = FirstEntryPending && launch.DirectToGame ? TelemetryNames.Via.Url : FirstEntryPending ? TelemetryNames.Via.Boot : TelemetryNames.Via.Select;
                EnterStage(flow.Stage);
            }
            FirstEntryPending = false;

            if (!string.IsNullOrEmpty(launch.Replay) && launch.DirectToGame && flow.Stage == launch.Level - 1)
            {
                session.Replay(launch.Replay);
                launch.Replay = ""; // once per launch
            }

            if (!string.IsNullOrEmpty(launch.Screenshot))
                StartCoroutine(ScreenshotOnce.Run(launch.Screenshot, () =>
                {
                    var s = session.State;
                    return $"level {flow.Stage + 1}, status {s.Status}, used {s.Used}, bodies {s.Bodies}";
                }));
        }

        void OnDestroy()
        {
            recorder?.Dispose();
            if (flow != null) flow.Changed -= OnFlowChanged;
            if (save != null) save.SettingsChanged -= ApplyVolume;
        }

        // ---------- Flow ----------

        void OnFlowChanged(AppState from, AppState to)
        {
            if (to == AppState.Game) EnterStage(flow.Stage);
            hud.ShowResult(to == AppState.Result, session.State, flow.Stage, levels.Length);
        }

        void EnterStage(int stage)
        {
            stage = Mathf.Clamp(stage, 0, levels.Length - 1);
            StageLeaving?.Invoke(stage);
            loadedStage = stage;
            session.Load(levels[stage]);
            save.Progress.lastStage = stage;
            StageEntered?.Invoke(stage, nextVia);
            nextVia = TelemetryNames.Via.Select;
        }

        /// Stage buttons, [ and ]. Goes through AppFlow (Game -> Game, or Result -> Game).
        public void SelectStage(int idx)
        {
            if (idx < 0 || idx >= levels.Length) return;
            nextVia = TelemetryNames.Via.Select;
            flow.GoToGame(idx);
        }

        public void NextLevel()
        {
            if (flow.Stage >= levels.Length - 1) return;
            nextVia = TelemetryNames.Via.Next;
            flow.GoToGame(flow.Stage + 1);
        }

        /// Result panel "다시 하기" after a clear: a fresh attempt at the same stage.
        public void Again()
        {
            nextVia = TelemetryNames.Via.Again;
            flow.GoToGame(flow.Stage);
        }

        public void OpenStageSelect()
        {
            save.SaveProgress();
            flow.Go(AppState.StageSelect);
        }

        // ---------- Input ----------

        void Update()
        {
            if (hud.SettingsOpen) return;
            var kb = Keyboard.current;
            if (kb != null)
            {
                if (kb.upArrowKey.wasPressedThisFrame || kb.wKey.wasPressedThisFrame) Send(Command.Move(Dir.Up));
                else if (kb.downArrowKey.wasPressedThisFrame || kb.sKey.wasPressedThisFrame) Send(Command.Move(Dir.Down));
                else if (kb.leftArrowKey.wasPressedThisFrame || kb.aKey.wasPressedThisFrame) Send(Command.Move(Dir.Left));
                else if (kb.rightArrowKey.wasPressedThisFrame || kb.dKey.wasPressedThisFrame) Send(Command.Move(Dir.Right));
                else if (kb.kKey.wasPressedThisFrame) Send(Command.Keep);
                else if (kb.xKey.wasPressedThisFrame) Send(Command.Switch);
                else if (kb.zKey.wasPressedThisFrame || kb.backspaceKey.wasPressedThisFrame) Send(Command.Undo);
                else if (kb.rKey.wasPressedThisFrame) Restart();
                else if (kb.hKey.wasPressedThisFrame) ShowHint();
                else if (kb.leftBracketKey.wasPressedThisFrame) SelectStage(flow.Stage - 1);
                else if (kb.rightBracketKey.wasPressedThisFrame) SelectStage(flow.Stage + 1);
                else if ((kb.enterKey.wasPressedThisFrame || kb.numpadEnterKey.wasPressedThisFrame) && flow.State == AppState.Result) NextLevel();
                else if (kb.escapeKey.wasPressedThisFrame) OpenStageSelect();
            }

            var mouse = Mouse.current;
            if (mouse != null && mouse.leftButton.wasPressedThisFrame && !PointerOverUi())
                ClickCell(mouse.position.ReadValue());
        }

        static bool PointerOverUi() => EventSystem.current != null && EventSystem.current.IsPointerOverGameObject();

        void ClickCell(Vector2 screen)
        {
            int cell = board.Grid.RayToCell(cam.ScreenPointToRay(screen));
            var s = session.State;
            if (cell < 0 || s == null) return;
            var l = s.Level;
            int dx = l.X(cell) - l.X(s.Pos), dy = l.Y(cell) - l.Y(s.Pos);
            if (dx == 0 && dy == -1) Send(Command.Move(Dir.Up));
            else if (dx == 0 && dy == 1) Send(Command.Move(Dir.Down));
            else if (dx == -1 && dy == 0) Send(Command.Move(Dir.Left));
            else if (dx == 1 && dy == 0) Send(Command.Move(Dir.Right));
        }

        /// Every input goes here. The session decides whether it applies now, is queued, or is dropped.
        public void Send(Command cmd)
        {
            // In Result (after a clear) only Restart is meaningful: it starts a new attempt.
            if (flow.State == AppState.Result)
            {
                if (cmd.Type == CommandType.Restart) Again();
                return;
            }
            session.Send(cmd);
        }

        public void Restart() => Send(Command.Restart);

        /// The solver starts from a fresh stage, so the hint is the full route from the beginning (same as the prototype).
        public void ShowHint()
        {
            var level = session.Level;
            if (level == null) return;
            if (!hintCache.TryGetValue(loadedStage, out var text))
            {
                var sol = Solver.Solve(level);
                if (sol == null) text = "풀이를 찾지 못했다.";
                else
                {
                    var sb = new StringBuilder("처음부터의 최단 풀이: ");
                    foreach (var a in sol.Path)
                        sb.Append(a switch { Act.Up => "↑", Act.Down => "↓", Act.Left => "←", Act.Right => "→", Act.Keep => " KEEP ", _ => " SWITCH " });
                    text = sb.ToString();
                }
                hintCache[loadedStage] = text;
            }
            message = text;
            HintShown?.Invoke();
            Refresh();
        }

        // ---------- Session updates ----------

        void OnSessionUpdated(SessionUpdate u)
        {
            switch (u.Kind)
            {
                case SessionUpdateKind.Rebuild:
                    message = u.State.Level.Hint;
                    break;
                case SessionUpdateKind.Feedback:
                    if (u.Result != null && u.Result.Has(GameEventType.Bump))
                    {
                        Play(assets.sfxBump);
                        board.Bump(FirstAt(u.Result, GameEventType.Bump));
                    }
                    else if (u.State.Status == Status.Choose && u.Command.Type == CommandType.Move)
                    {
                        message = ChooseNudge;
                        hud.NudgeChoice();
                    }
                    break;
                default:
                    if (u.Result != null)
                    {
                        foreach (var e in u.Result.Events)
                        {
                            if (Messages.TryGetValue(e.Type, out var m)) message = m;
                            if (e.Type == GameEventType.Step) message = e.StepIdx == Rules.Steps - 1 ? "다음 걸음이 행운의 7번째 걸음이다." : "";
                        }
                        PlaySounds(u.Result);
                    }
                    break;
            }

            var s = u.State;
            if (s.Status == Status.Win && u.Kind == SessionUpdateKind.Present)
            {
                save.Progress.MarkCleared(flow.Stage, s.Level.Bodies - s.Bodies + 1);
                save.SaveProgress();
                Refresh();
                // The Result panel opens in OnPresented, after the walk to the exit has played.
                return;
            }
            Refresh();
        }

        /// A presentation finished (docs/architecture.md 4.2). A clear shows the Result panel only now.
        void OnPresented(State s)
        {
            if (s.Status == Status.Win && flow.State == AppState.Game) flow.Go(AppState.Result);
        }

        static int FirstAt(StepResult r, GameEventType t)
        {
            foreach (var e in r.Events) if (e.Type == t) return e.At;
            return -1;
        }

        void PlaySounds(StepResult r)
        {
            foreach (var e in r.Events)
            {
                if (e.StepIdx == Rules.Steps) Play(assets.sfxLucky);
                switch (e.Type)
                {
                    case GameEventType.Step: Play(assets.sfxStep, 0.9f + 0.06f * e.StepIdx); break;
                    case GameEventType.Bump: Play(assets.sfxBump); break;
                    case GameEventType.Crumble: Play(assets.sfxCrumble); break;
                    case GameEventType.Stone: Play(assets.sfxStone); break;
                    case GameEventType.Switch:
                    case GameEventType.Flip: Play(assets.sfxSwitch); break;
                    case GameEventType.Bridge:
                    case GameEventType.Seal: Play(assets.sfxBridge); break;
                    case GameEventType.Fall: Play(assets.sfxFall); break;
                    case GameEventType.Win: Play(assets.sfxWin); break;
                    case GameEventType.Lose: Play(assets.sfxLose); break;
                    case GameEventType.Undo:
                    case GameEventType.Restart: Play(assets.sfxUndo); break;
                }
            }
        }

        void Play(AudioClip clip, float pitch = 1f)
        {
            if (clip == null) return;
            sfx.pitch = pitch;
            sfx.PlayOneShot(clip);
        }

        void ApplyVolume(SettingsData s)
        {
            AudioListener.volume = Mathf.Clamp01(s.masterVolume);
            if (sfx != null) sfx.volume = Mathf.Clamp01(s.sfxVolume);
        }

        void Refresh() => hud.Refresh(session.State, flow.Stage, levels.Length, message, save.Progress);
    }
}
