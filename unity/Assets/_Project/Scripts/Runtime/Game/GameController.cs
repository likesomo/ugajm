using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using SevenSteps.Core;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.InputSystem;
using UnityEngine.InputSystem.UI;

namespace SevenSteps.Game
{
    /// <summary>
    /// Game shell: input, sound, save, stage flow. Holds the current State and changes it only through Rules.Dispatch.
    /// Board drawing is BoardView, screen UI is HudView. Open a stage directly with startLevel / replay (editor)
    /// or ?level=8&amp;replay=LRRRRDDK... in the WebGL URL (same format as the web prototype).
    /// </summary>
    public sealed class GameController : MonoBehaviour
    {
        const string SaveKey = "seven-steps-cleared";

        static readonly Dictionary<GameEventType, string> Messages = new Dictionary<GameEventType, string>
        {
            { GameEventType.Choose, "행운의 7번째 걸음. 이 몸을 어떻게 할까?" },
            { GameEventType.Stone, "KEEP. 몸이 석상이 되었다. 다음 몸은 출발점에서 깨어난다." },
            { GameEventType.Switch, "SWITCH. 이 자리가 새 출발점이 되었다." },
            { GameEventType.Bridge, "7번째 걸음으로 구덩이에 몸을 던졌다. 다리가 되었다." },
            { GameEventType.Seal, "금 간 바닥 위에서 석상이 되었다. 바닥이 영원히 굳었다." },
            { GameEventType.Fall, "구덩이에 떨어졌다. 7번째 걸음이 아니면 아무것도 남지 않는다." },
            { GameEventType.Vanish, "출발점에서는 석상이 될 수 없다. 몸 하나를 잃었다." },
            { GameEventType.Crumble, "금 간 바닥이 무너졌다." },
            { GameEventType.Win, "7번째 걸음으로 출구에 닿았다!" },
            { GameEventType.Lose, "몸을 모두 잃었다. Z로 되돌리거나 R로 다시 시작." },
            { GameEventType.Undo, "한 걸음 되돌렸다." },
            { GameEventType.Restart, "처음부터." },
        };

        [Tooltip("Generated by Seven Steps > Build Assets and Scene")]
        public GameAssets assets;
        [Tooltip("1-based stage opened first")]
        public int startLevel = 1;
        [Tooltip("Optional replay applied after loading (U D L R move, K keep, X switch)")]
        public string replay = "";

        Level[] levels;
        int levelIdx;
        State state;
        string message;
        HudView hud;
        BoardView board;
        AudioSource sfx;
        Camera cam;
        readonly HashSet<int> cleared = new HashSet<int>();

        public int LevelIndex => levelIdx;
        public int LevelCount => levels.Length;

        void Awake()
        {
            Application.targetFrameRate = 60;
            Ui.Font = assets.font;
            var file = JsonUtility.FromJson<LevelFileDto>(assets.levelsJson.text);
            levels = file.levels.Select(d => d.ToLevel()).ToArray();

            cam = Camera.main;
            cam.clearFlags = CameraClearFlags.SolidColor;
            cam.backgroundColor = assets.background;
            sfx = gameObject.AddComponent<AudioSource>();
            sfx.playOnAwake = false;

            if (FindAnyObjectByType<EventSystem>() == null)
                new GameObject("EventSystem", typeof(EventSystem), typeof(InputSystemUIInputModule));

            hud = new HudView(this, levels.Length);
            board = gameObject.AddComponent<BoardView>();
            board.Init(assets, hud.LabelLayer, cam);
            LoadCleared();

            ReadUrlParams(ref startLevel, ref replay);
            LoadLevel(Mathf.Clamp(startLevel - 1, 0, levels.Length - 1));
            if (!string.IsNullOrEmpty(replay))
            {
                foreach (char c in replay)
                    if (Rules.TryParseLetter(c, out var act)) state = Rules.Dispatch(state, Command.FromAct(act)).State;
                board.Show(state, null, false);
                Refresh();
            }

            // Smoke test: "Seven Steps.exe" -level 3 -replay DURRRRR -screenshot out.png  -> saves a frame and quits.
            var args = Environment.GetCommandLineArgs();
            int shot = Array.IndexOf(args, "-screenshot");
            if (shot >= 0 && shot + 1 < args.Length) StartCoroutine(ScreenshotAndQuit(args[shot + 1]));
        }

        System.Collections.IEnumerator ScreenshotAndQuit(string path)
        {
            yield return new WaitForSeconds(1.5f);
            yield return new WaitForEndOfFrame();
            ScreenCapture.CaptureScreenshot(path);
            yield return new WaitForSeconds(0.5f);
            Debug.Log($"[SevenSteps] Screenshot {path} (level {levelIdx + 1}, status {state.Status}, used {state.Used}, bodies {state.Bodies})");
            Application.Quit();
        }

        void Update()
        {
            var kb = Keyboard.current;
            if (kb != null)
            {
                if (Pressed(kb.upArrowKey, kb.wKey)) Send(Command.Move(Dir.Up));
                else if (Pressed(kb.downArrowKey, kb.sKey)) Send(Command.Move(Dir.Down));
                else if (Pressed(kb.leftArrowKey, kb.aKey)) Send(Command.Move(Dir.Left));
                else if (Pressed(kb.rightArrowKey, kb.dKey)) Send(Command.Move(Dir.Right));
                else if (kb.kKey.wasPressedThisFrame) Send(Command.Keep);
                else if (kb.xKey.wasPressedThisFrame) Send(Command.Switch);
                else if (Pressed(kb.zKey, kb.backspaceKey)) Send(Command.Undo);
                else if (kb.rKey.wasPressedThisFrame) Send(Command.Restart);
                else if (kb.hKey.wasPressedThisFrame) ShowHint();
                else if (kb.leftBracketKey.wasPressedThisFrame && levelIdx > 0) LoadLevel(levelIdx - 1);
                else if (kb.rightBracketKey.wasPressedThisFrame && levelIdx < levels.Length - 1) LoadLevel(levelIdx + 1);
                else if (Pressed(kb.enterKey, kb.numpadEnterKey) && state.Status == Status.Win) NextLevel();
            }

            var mouse = Mouse.current;
            if (mouse != null && mouse.leftButton.wasPressedThisFrame && !PointerOverUi())
                ClickCell(mouse.position.ReadValue());
        }

        static bool Pressed(params UnityEngine.InputSystem.Controls.KeyControl[] keys) => keys.Any(k => k.wasPressedThisFrame);

        static bool PointerOverUi() => EventSystem.current != null && EventSystem.current.IsPointerOverGameObject();

        void ClickCell(Vector2 screen)
        {
            var ray = cam.ScreenPointToRay(screen);
            if (!new Plane(Vector3.up, Vector3.zero).Raycast(ray, out float dist)) return;
            int cell = board.CellAt(ray.GetPoint(dist));
            if (cell < 0) return;
            var l = state.Level;
            int dx = l.X(cell) - l.X(state.Pos), dy = l.Y(cell) - l.Y(state.Pos);
            if (dx == 0 && dy == -1) Send(Command.Move(Dir.Up));
            else if (dx == 0 && dy == 1) Send(Command.Move(Dir.Down));
            else if (dx == -1 && dy == 0) Send(Command.Move(Dir.Left));
            else if (dx == 1 && dy == 0) Send(Command.Move(Dir.Right));
        }

        public void Send(Command cmd)
        {
            var prev = state;
            var r = Rules.Dispatch(state, cmd);
            state = r.State;
            foreach (var e in r.Events)
            {
                if (Messages.TryGetValue(e.Type, out var m)) message = m;
                if (e.Type == GameEventType.Step) message = e.StepIdx == Rules.Steps - 1 ? "다음 걸음이 행운의 7번째 걸음이다." : "";
            }
            PlaySounds(r);
            if (state.Status == Status.Win && cleared.Add(levelIdx)) SaveCleared();

            bool moved = !ReferenceEquals(state, prev);
            bool animate = moved && (cmd.Type == CommandType.Move || cmd.Type == CommandType.Keep || cmd.Type == CommandType.Switch);
            board.Show(state, r, animate);
            Refresh();
        }

        void PlaySounds(StepResult r)
        {
            foreach (var e in r.Events)
            {
                if (e.StepIdx == Rules.Steps) Play(assets.sfxLucky);
                switch (e.Type)
                {
                    case GameEventType.Step: Play(assets.sfxStep, 0.9f + 0.06f * e.StepIdx); break;
                    case GameEventType.Bump: Play(assets.sfxBump); break;
                    case GameEventType.Crumble: Play(assets.sfxCrumble); break;
                    case GameEventType.Stone: Play(assets.sfxStone); break;
                    case GameEventType.Switch: Play(assets.sfxSwitch); break;
                    case GameEventType.Bridge:
                    case GameEventType.Seal: Play(assets.sfxBridge); break;
                    case GameEventType.Fall: Play(assets.sfxFall); break;
                    case GameEventType.Win: Play(assets.sfxWin); break;
                    case GameEventType.Lose: Play(assets.sfxLose); break;
                    case GameEventType.Undo:
                    case GameEventType.Restart: Play(assets.sfxUndo); break;
                }
            }
        }

        void Play(AudioClip clip, float pitch = 1f)
        {
            if (clip == null) return;
            sfx.pitch = pitch;
            sfx.PlayOneShot(clip);
        }

        public void LoadLevel(int idx)
        {
            levelIdx = idx;
            state = Rules.NewState(levels[idx]);
            message = levels[idx].Hint;
            board.Build(state);
            Refresh();
        }

        public void NextLevel()
        {
            if (levelIdx < levels.Length - 1) LoadLevel(levelIdx + 1);
        }

        /// The solver starts from a fresh stage, so the hint is the full route from the beginning (same as the prototype).
        public void ShowHint()
        {
            var sol = Solver.Solve(state.Level);
            if (sol == null) { message = "풀이를 찾지 못했다."; Refresh(); return; }
            var sb = new StringBuilder("처음부터의 최단 풀이: ");
            foreach (var a in sol.Path)
                sb.Append(a switch { Act.Up => "↑", Act.Down => "↓", Act.Left => "←", Act.Right => "→", Act.Keep => " KEEP ", _ => " SWITCH " });
            message = sb.ToString();
            Refresh();
        }

        void Refresh() => hud.Refresh(state, levelIdx, levels.Length, message, cleared);

        void LoadCleared()
        {
            foreach (var part in PlayerPrefs.GetString(SaveKey, "").Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries))
                if (int.TryParse(part, out int k)) cleared.Add(k);
        }

        void SaveCleared()
        {
            PlayerPrefs.SetString(SaveKey, string.Join(",", cleared.OrderBy(k => k)));
            PlayerPrefs.Save();
        }

        /// WebGL: ?level=8&amp;replay=LRRK...  Desktop: "Seven Steps.exe" -level 8 -replay LRRK...
        static void ReadUrlParams(ref int level, ref string replay)
        {
            var args = Environment.GetCommandLineArgs();
            for (int k = 0; k + 1 < args.Length; k++)
            {
                if (args[k] == "-level" && int.TryParse(args[k + 1], out int lv)) level = lv;
                if (args[k] == "-replay" && !args[k + 1].StartsWith("-")) replay = args[k + 1];
            }
            string url = Application.absoluteURL;
            int q = string.IsNullOrEmpty(url) ? -1 : url.IndexOf('?');
            if (q < 0) return;
            foreach (var kv in url.Substring(q + 1).Split('&'))
            {
                var p = kv.Split('=');
                if (p.Length != 2) continue;
                if (p[0] == "level" && int.TryParse(p[1], out int n)) level = n;
                if (p[0] == "replay") replay = Uri.UnescapeDataString(p[1]);
            }
        }
    }
}
